import matplotlib.pyplot as plt
import numpy as np

"""### Part 1a - Shear Diagram

You will create your shear diagram in the code block below.

"""

L = 6
R_A = 170
R_B = 410
P_1 = 100
q_1 = 120
q_2 = 120

x = np.linspace(0,L,500)

v = np.zeros_like(x)

for i in range(len(x)):
    if x[i] < 2:
        v[i] = R_A - (q_1 * x[i])
    elif 2 < x[i] < 4:
        v[i] = R_A - (q_1 * 2) - P_1
    elif x[i] > 4:
        v[i] = R_A - (q_1 * 2) - P_1 + R_B - (q_2 * (x[i] - 4))

x_plot = np.repeat(x, 2)[1:]
v_plot = np.repeat(v, 2)[:-1]

plt.figure(figsize=(10, 6))
plt.fill_between(x_plot, v_plot, 0, color="skyblue", alpha=0.7)
plt.plot(x_plot, v_plot, color="navy", linewidth=2)

plt.plot(x_plot, v_plot)
plt.xlabel("Position, x (ft)")
plt.ylabel("Shear, V (lb)")
plt.title("Shear Diagram")
plt.grid(True)
plt.show()

"""### Part 1b - Moment Diagram

You will create your moment diagram in the code block below.
"""

L = 6
R_A = 170
R_B = 410
P_1 = 100
q_1 = 120
q_2 = 120

x = np.linspace(0,L,500)

M = np.zeros_like(x)

for i in range(len(x)):
    if x[i] < 2:
        M[i] = (R_A * x[i]) - (q_1 * x[i]**2 / 2)
    elif 2 < x[i] < 4:
        M[i] = (
            (R_A * x[i])
            - (q_1 * 2 * (x[i] - 1))
            - (P_1 * (x[i] - 2))
        )
    elif x[i] > 4:
        M[i] = (
            (R_A * x[i])
            - (q_1 * 2 * (x[i] - 1))
            - (P_1 * (x[i] - 2))
            + (R_B * (x[i] - 4))
            - (q_2 * (x[i] - 4) * ((x[i] - 4) / 2))
        )

plt.figure(figsize=(8, 4))
plt.fill_between(x, M, 0, color="purple", alpha=0.7)
plt.plot(x, M, color="gold", linewidth=2)

plt.axhline(0, color="black", linewidth=1)
plt.xlim(0, L)
plt.ylim(-260, 140)
plt.xlabel("x (ft)")
plt.ylabel("M (lb-ft)")
plt.title("Moment Diagram")
plt.show()

"""### Part 2 - Pasadena Precipitation Data

You will now create a graph using Pasadena Temperature Data from 2013-2014.

### Numpy Array Creation & Slicing

Create and slice the array to create the x and y-axis values. These will correspond to the following columns in the CSV linked on readthedocs:

*   x - Date
*   y_1 - High Temperature
*   y_2 - Low Temperature
"""

import csv
from datetime import datetime
import numpy as np

date = []
high_temperature = []
low_temperature = []

with open("2013-2014-Pasadena-Temperature-Data.csv", newline="") as file:
    reader = csv.reader(file)
    next(reader)  # Skip the header row

    for row in reader:
        date.append(datetime.strptime(row[0], "%m/%d/%y"))
        high_temperature.append(float(row[1]))
        low_temperature.append(float(row[2]))

x = np.array(date)
y_1 = np.array(high_temperature)
y_2 = np.array(low_temperature)

"""### Graphing the Data

Plot x, y_1 and y_2 with the elements shown in the instructions on the HW page.
"""

import matplotlib.pyplot as plt
import matplotlib.dates as mdates

# Plot the data
fig, ax = plt.subplots(figsize=(6, 5))

ax.plot(x, y_1, label="High Temperature", color="red", linewidth=2)
ax.plot(x, y_2, label="Low Temperature", color="blue", linewidth=2)

# Add labels and title
ax.set_title("Pasadena Temperature Data 2013-2014")
ax.set_xlabel("Date")
ax.set_ylabel("Degrees (°F)")

# Add legend and grid
ax.legend()
ax.grid(True, alpha=0.3)

# Format x-axis dates
ax.xaxis.set_major_formatter(mdates.DateFormatter("%Y-%m"))
ax.xaxis.set_major_locator(mdates.MonthLocator(interval=2))
plt.xticks(rotation=45)

plt.tight_layout()
plt.show()

